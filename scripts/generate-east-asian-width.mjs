// Regenerates the East Asian Width "wide" table (code points whose East_Asian_Width is W or F) used by the terminal
// line estimate of the continuous lyric strip (ADR 0041 D10): one range list, written out for Rust, JS and Kotlin so
// the three implementations cannot drift (tests/east-asian-width.test.mjs checks they are identical).
// Usage: node scripts/generate-east-asian-width.mjs <path to EastAsianWidth-<version>.txt>
// Source: https://www.unicode.org/Public/<version>/ucd/EastAsianWidth.txt (Unicode data, Unicode License v3).
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { basename } from 'node:path';

const input = process.argv[2];
if (!input) {
  console.error('usage: node scripts/generate-east-asian-width.mjs <EastAsianWidth-<version>.txt>');
  process.exit(1);
}
const raw = readFileSync(input);
const text = raw.toString('utf8');
const version = /^# EastAsianWidth-(\d+\.\d+\.\d+)\.txt/m.exec(text)?.[1];
if (!version) throw new Error('not an EastAsianWidth.txt (no version header)');
const sha256 = createHash('sha256').update(raw).digest('hex');

/** @type {[number, number][]} */
const ranges = [];
for (const line of text.split(/\r?\n/)) {
  const m = /^([0-9A-F]{4,6})(?:\.\.([0-9A-F]{4,6}))?\s*;\s*(\w+)/.exec(line);
  if (!m || (m[3] !== 'W' && m[3] !== 'F')) continue;
  ranges.push([parseInt(m[1], 16), parseInt(m[2] ?? m[1], 16)]);
}
// The header's documented defaults: unassigned code points in these blocks / planes are W too.
for (const [from, to] of [[0x3400, 0x4dbf], [0x4e00, 0x9fff], [0xf900, 0xfaff], [0x20000, 0x2fffd], [0x30000, 0x3fffd]]) {
  ranges.push([from, to]);
}
ranges.sort((a, b) => a[0] - b[0]);
/** @type {[number, number][]} */
const merged = [];
for (const [from, to] of ranges) {
  const last = merged[merged.length - 1];
  if (last && from <= last[1] + 1) last[1] = Math.max(last[1], to);
  else merged.push([from, to]);
}

const hex = (n) => `0x${n.toString(16).toUpperCase().padStart(4, '0')}`;
const header = (comment) => [
  `${comment} GENERATED by scripts/generate-east-asian-width.mjs from ${basename(input)}; do not edit by hand.`,
  `${comment} Source: Unicode ${version}, https://www.unicode.org/Public/${version}/ucd/EastAsianWidth.txt`,
  `${comment} (SHA-256 ${sha256}), Unicode License v3.`,
  `${comment} Ranges of East_Asian_Width W or F, plus the file's documented W defaults for unassigned code points`,
  `${comment} (CJK blocks, planes 2 and 3); adjacent ranges merged.`,
];
const rows = (indent, perLine, fmt) => {
  const out = [];
  for (let i = 0; i < merged.length; i += perLine) out.push(indent + merged.slice(i, i + perLine).map(fmt).join(' '));
  return out.join('\n');
};

const rust = `${header('//').join('\n')}

/// Inclusive code point ranges whose East Asian Width is Wide or Fullwidth, sorted and disjoint.
pub const WIDE_RANGES: &[(u32, u32)] = &[
${rows('    ', 1, ([a, b]) => `(${hex(a)}, ${hex(b)}),`)}
];

/// Whether \`c\` is East Asian Wide (W) or Fullwidth (F).
pub fn is_east_asian_wide(c: char) -> bool {
    let cp = c as u32;
    WIDE_RANGES
        .binary_search_by(|&(from, to)| {
            if to < cp {
                core::cmp::Ordering::Less
            } else if from > cp {
                core::cmp::Ordering::Greater
            } else {
                core::cmp::Ordering::Equal
            }
        })
        .is_ok()
}
`;

const js = `${header('//').join('\n')}

/** Inclusive code point ranges (flat pairs: from, to) whose East Asian Width is W or F, sorted and disjoint. */
export const EAST_ASIAN_WIDE_RANGES = Object.freeze([
${rows('  ', 4, ([a, b]) => `${hex(a)}, ${hex(b)},`)}
]);

/** Whether the code point \`cp\` is East Asian Wide (W) or Fullwidth (F). @param {number} cp */
export function isEastAsianWide(cp) {
  let lo = 0;
  let hi = EAST_ASIAN_WIDE_RANGES.length / 2 - 1;
  while (lo <= hi) {
    const mid = (lo + hi) >> 1;
    if (EAST_ASIAN_WIDE_RANGES[mid * 2 + 1] < cp) lo = mid + 1;
    else if (EAST_ASIAN_WIDE_RANGES[mid * 2] > cp) hi = mid - 1;
    else return true;
  }
  return false;
}
`;

const kotlin = `${header('//').join('\n')}
package com.moemusicplayer.mediaindex

object EastAsianWidth {
    /** Inclusive code point ranges (flat pairs: from, to) whose East Asian Width is W or F, sorted and disjoint. */
    val WIDE_RANGES = intArrayOf(
${rows('        ', 4, ([a, b]) => `${hex(a)}, ${hex(b)},`)}
    )

    /** Whether the code point \`cp\` is East Asian Wide (W) or Fullwidth (F). */
    fun isWide(cp: Int): Boolean {
        var lo = 0
        var hi = WIDE_RANGES.size / 2 - 1
        while (lo <= hi) {
            val mid = (lo + hi) ushr 1
            when {
                WIDE_RANGES[mid * 2 + 1] < cp -> lo = mid + 1
                WIDE_RANGES[mid * 2] > cp -> hi = mid - 1
                else -> return true
            }
        }
        return false
    }
}
`;

writeFileSync(new URL('../crates/player-lyrics-rules/src/east_asian_width.rs', import.meta.url), rust);
writeFileSync(new URL('../src/lib/east-asian-width.js', import.meta.url), js);
writeFileSync(
  new URL('../plugins/tauri-plugin-media-index/android/src/main/java/com/moemusicplayer/mediaindex/EastAsianWidth.kt', import.meta.url),
  kotlin,
);
console.log(`Unicode ${version}: ${merged.length} wide ranges`);
