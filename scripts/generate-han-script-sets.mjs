// Regenerates the 200 distinctive Traditional / Simplified Han pairs the font script detection counts (ADR 0042):
// crates/player-fonts/src/han_forms.rs.
// Usage: node scripts/generate-han-script-sets.mjs <extracted Unihan folder> <Unihan.zip>
// Source: https://www.unicode.org/Public/<version>/ucd/Unihan.zip (Unicode data, Unicode License v3). The zip is only
// hashed for the header; the fields are read from the extracted Unihan_*.txt files.
//
// Rule: Simplified characters by real frequency (kHanyuPinlu, the counts of every reading summed), keeping one only if
// it is not in Big5 (no kBigFive) and has a kTraditionalVariant other than itself. Its Traditional form is the most
// common candidate that is in Big5 and not in GB2312 (no kGB0): one with kGradeLevel first (lowest grade), else one in
// the Big5 common range A440–C67E; a pair whose only candidates are outside both is dropped, as is a Traditional form
// already taken by a more frequent pair, and so are the Traditional forms in UNCOMMON (in Big5 level 1 without a
// grade, yet rare in Traditional text: 呐 counts its particle use, which Traditional text writes 呢). The first 200
// pairs are written.
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join } from 'node:path';

const [dir, zip] = process.argv.slice(2);
if (!dir || !zip) {
  console.error('usage: node scripts/generate-han-script-sets.mjs <extracted Unihan folder> <Unihan.zip>');
  process.exit(1);
}
const COUNT = 200;
const UNCOMMON = new Set(['吶'].map((c) => c.codePointAt(0)));
const zipSha256 = createHash('sha256').update(readFileSync(zip)).digest('hex').toUpperCase();

/** field → Map(code point → value) for the wanted fields of one Unihan file. */
function readFields(file, wanted) {
  const text = readFileSync(join(dir, file), 'utf8');
  const fields = new Map(wanted.map((name) => [name, new Map()]));
  let version = null;
  for (const line of text.split(/\r?\n/)) {
    if (line.startsWith('#')) {
      version ??= /^# Unicode Version (\d+\.\d+\.\d+)/.exec(line)?.[1] ?? null;
      continue;
    }
    const m = /^U\+([0-9A-F]{4,6})\t(\w+)\t(.*)$/.exec(line);
    if (!m || !fields.has(m[2])) continue;
    fields.get(m[2]).set(parseInt(m[1], 16), m[3]);
  }
  if (!version) throw new Error(`${file}: no "Unicode Version" header`);
  return { fields, version };
}

const readings = readFields('Unihan_Readings.txt', ['kHanyuPinlu']);
const variants = readFields('Unihan_Variants.txt', ['kTraditionalVariant']);
const mappings = readFields('Unihan_OtherMappings.txt', ['kBigFive', 'kGB0']);
const dictionary = readFields('Unihan_DictionaryLikeData.txt', ['kGradeLevel']);
const versions = new Set([readings, variants, mappings, dictionary].map((r) => r.version));
if (versions.size !== 1) throw new Error(`Unihan files disagree on the version: ${[...versions]}`);
const [version] = versions;

const pinlu = readings.fields.get('kHanyuPinlu');
const traditionalVariant = variants.fields.get('kTraditionalVariant');
const bigFive = mappings.fields.get('kBigFive');
const gb0 = mappings.fields.get('kGB0');
const gradeLevel = dictionary.fields.get('kGradeLevel');

const frequency = (code) =>
  [...pinlu.get(code).matchAll(/\((\d+)\)/g)].reduce((sum, m) => sum + Number(m[1]), 0);
const commonBig5 = (code) => {
  const big5 = parseInt(bigFive.get(code), 16);
  return big5 >= 0xa440 && big5 <= 0xc67e;
};
/** Lower is more common: graded forms by grade, then the Big5 common range; null = uncommon. */
const rank = (code) => {
  if (gradeLevel.has(code)) return Number(gradeLevel.get(code));
  if (commonBig5(code)) return 100;
  return null;
};

const simplified = [...pinlu.keys()]
  .map((code) => ({ code, count: frequency(code) }))
  .sort((a, b) => b.count - a.count || a.code - b.code);
const pairs = [];
const taken = new Set();
for (const { code, count } of simplified) {
  if (bigFive.has(code) || !traditionalVariant.has(code)) continue;
  const candidates = traditionalVariant
    .get(code)
    .split(/\s+/)
    .map((v) => parseInt(v.replace(/^U\+/, ''), 16))
    .filter((t) => t !== code && bigFive.has(t) && !gb0.has(t) && rank(t) !== null && !taken.has(t) && !UNCOMMON.has(t))
    .sort((a, b) => rank(a) - rank(b) || parseInt(bigFive.get(a), 16) - parseInt(bigFive.get(b), 16));
  if (candidates.length === 0) continue;
  taken.add(candidates[0]);
  pairs.push({ simplified: code, traditional: candidates[0], count });
}
if (pairs.length < COUNT) throw new Error(`only ${pairs.length} pairs`);
const chosen = pairs.slice(0, COUNT);

const ch = (code) => `'${String.fromCodePoint(code)}'`;
const rows = (codes) => {
  const out = [];
  for (let i = 0; i < codes.length; i += 16) out.push(`    ${codes.slice(i, i + 16).map(ch).join(', ')},`);
  return out.join('\n');
};
const source = `// GENERATED by scripts/generate-han-script-sets.mjs; do not edit by hand.
// Source: Unihan ${version} (Unihan.zip SHA-256 ${zipSha256}), Unicode License v3.
// Regenerate: node scripts/generate-han-script-sets.mjs <extracted Unihan folder> <Unihan.zip>
// The ${COUNT} most frequent Simplified characters (kHanyuPinlu) outside Big5 with a Traditional form in Big5 and
// outside GB2312 (kTraditionalVariant; graded or Big5 A440–C67E; not 吶). Same index = one pair (of ${pairs.length} found).

/// Traditional forms whose Simplified forms differ: index \`i\` pairs with \`SIMPLIFIED_FORMS[i]\`.
pub(crate) const TRADITIONAL_FORMS: [char; ${COUNT}] = [
${rows(chosen.map((p) => p.traditional))}
];

/// Simplified forms, not in Big5: index \`i\` pairs with \`TRADITIONAL_FORMS[i]\`.
pub(crate) const SIMPLIFIED_FORMS: [char; ${COUNT}] = [
${rows(chosen.map((p) => p.simplified))}
];
`;
const out = new URL('../crates/player-fonts/src/han_forms.rs', import.meta.url);
writeFileSync(out, source);
console.log(`${pairs.length} pairs; wrote the first ${COUNT} (last: ${String.fromCodePoint(chosen.at(-1).simplified)}/${String.fromCodePoint(chosen.at(-1).traditional)} ${chosen.at(-1).count})`);
console.log(chosen.map((p) => `${String.fromCodePoint(p.simplified)}/${String.fromCodePoint(p.traditional)}`).join(' '));
